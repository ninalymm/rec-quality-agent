def build_history(cats, offset):
    """从 interest_categories 里挑 4 条标题，至少覆盖 2 个类目。"""
    picked = []
    i = 0
    while len(picked) < 4:
        cat = cats[i % len(cats)]
        bank = TITLES[cat]
        title = bank[(offset + len(picked) * 3) % len(bank)]
        if title not in picked:
            picked.append(title)
        i += 1
        if i > 40:  # 兜底，避免死循环
            break
    return "；".join("《%s》" % t for t in picked)

def profile(age, city, job, detail):
    return "%d 岁，%s，%s，%s。" % (age, city, job, detail)

