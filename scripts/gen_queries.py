def detail_for(cats, base=""):
    """按兴趣类目挑一条细节，保证不出现「说跑步却没跑步历史」。"""
    override = DETAIL_BY_JOB.get(base, {})
    for c in cats:
        if c in override:
            return override[c]
        if c in DETAIL:
            d = DETAIL[c]
            if c == "教育" and "全职带娃" not in base:
                continue  # 「孩子上小学」只给宝妈
            return d
    return ""


def pick(cat, role, offset, need):
    """从对应子库取标题，保证不重复。"""
    if cat == "技术":
        bank = TECH[ROLE_BANK.get(role, ("general", "generic"))[0]]
    elif cat == "职场":
        bank = WORK[ROLE_BANK.get(role, ("general", "generic"))[1]]
    else:
        bank = TITLES[cat]
    out = []
    i = 0
    while len(out) < need:
        t = bank[(offset + len(out) * 3) % len(bank)]
        if t not in out:
            out.append(t)
        i += 1
        if i > 50:
            break
    return out


def build_history(cats, role, offset, n=4):
    titles = []
    for i, cat in enumerate(cats):
        need = n // len(cats) + (1 if i < n % len(cats) else 0)
        titles += pick(cat, role, offset + i, need)
    return "；".join("《%s》" % t for t in titles[:n])


